"""RAG 线（检索增强生成）的包入口。

目录分工：
    offline/  离线侧：把标书文件解析成纯文本、清洗、分块、算向量、写进数据库。
              特点是"跑一次、耗时长"，由批处理脚本或消息队列驱动。
    online/   在线侧：一次检索请求的完整链路（双路召回 → 融合 → 重排 → 拼上下文）。
              特点是"毫秒级、每次评审都要跑几十次"。

为什么以前没有这个文件、程序也能 import？
Python 3 允许"命名空间包"：目录里没有 __init__.py 也能被当成包导入。
但那样有个坏处——路径拼错时（比如 rag/offlin/）报的是含糊的 ImportError，
而有 __init__.py 之后，导入失败会直接指出是哪个包不存在，排查快得多。
另外，包内做相对导入（from .offline import xxx）也依赖它是真正的包。
"""
